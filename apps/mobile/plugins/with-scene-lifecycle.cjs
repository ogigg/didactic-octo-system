const {
  IOSConfig,
  withAppDelegate,
  withInfoPlist,
} = require("@expo/config-plugins");

/**
 * Moves the iOS app to the UIScene lifecycle.
 *
 * Apps built with the iOS 27 SDK must adopt UIScene or iOS terminates them at
 * launch (UIKit's `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`
 * traps). The Expo SDK 54 AppDelegate template still creates the window and
 * starts React Native in `application(_:didFinishLaunchingWithOptions:)`, so
 * this plugin:
 *
 * 1. declares one window scene in Info.plist (`UIApplicationSceneManifest`);
 * 2. adds `SceneDelegate.swift`, which creates the window, starts React Native
 *    in it and forwards URLs and user activities to the AppDelegate, so Expo's
 *    app delegate subscribers (expo-linking, expo-router) and RCTLinkingManager
 *    keep receiving them;
 * 3. makes the AppDelegate keep its launch options for the scene delegate
 *    instead of creating the window itself.
 *
 * Expo prebuild regenerates ios/, so the fix has to live here. Remove this
 * plugin once the Expo template adopts UIScene itself.
 */
const SCENE_DELEGATE_CLASS = "$(PRODUCT_MODULE_NAME).SceneDelegate";
const MARKER = "// @generated sweaty-scene-lifecycle";

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: "Default Configuration",
        UISceneDelegateClassName: SCENE_DELEGATE_CLASS,
      },
    ],
  },
};

const SCENE_DELEGATE_SWIFT = `// Generated by plugins/with-scene-lifecycle.cjs. ios/ is regenerated by
// \`expo prebuild\`, so change the plugin instead of this file.
//
// Apps built with the iOS 27 SDK must adopt the UIScene lifecycle, or iOS
// terminates them at launch. This scene delegate creates the window and starts
// React Native, which the Expo AppDelegate template does at launch otherwise,
// and forwards URLs and user activities to the AppDelegate so Expo's app
// delegate subscribers and RCTLinkingManager still receive them.
import React
import UIKit

class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
      let appDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    // A cold launch from a link or a user activity arrives here rather than
    // in the app's launch options. Hand it to React Native the way the app
    // delegate path did, and to the AppDelegate for Expo's subscribers.
    var launchOptions = appDelegate.launchOptions ?? [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
      _ = appDelegate.application(UIApplication.shared, open: url, options: [:])
    }
    if let userActivity = connectionOptions.userActivities.first {
      launchOptions[.userActivityDictionary] = [
        "UIApplicationLaunchOptionsUserActivityKey": userActivity,
        "UIApplicationLaunchOptionsUserActivityTypeKey": userActivity.activityType,
      ]
      _ = appDelegate.application(
        UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let context = URLContexts.first else { return }
    var options: [UIApplication.OpenURLOptionsKey: Any] = [.openInPlace: context.options.openInPlace]
    if let sourceApplication = context.options.sourceApplication {
      options[.sourceApplication] = sourceApplication
    }
    if let annotation = context.options.annotation {
      options[.annotation] = annotation
    }
    _ = appDelegate?.application(UIApplication.shared, open: context.url, options: options)
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = appDelegate?.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

// The window + startReactNative block of the Expo SDK 54 AppDelegate template.
const TEMPLATE_WINDOW_BLOCK =
  /\n[ \t]*#if os\(iOS\) \|\| os\(tvOS\)\n[ \t]*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n[ \t]*factory\.startReactNative\(\n[ \t]*withModuleName: "main",\n[ \t]*in: window,\n[ \t]*launchOptions: launchOptions\)\n[ \t]*#endif\n/;
const TEMPLATE_FACTORY_PROPERTY =
  /\n([ \t]*)var reactNativeFactory: RCTReactNativeFactory\?\n/;

function adoptSceneLifecycle(appDelegate) {
  if (appDelegate.includes(MARKER)) {
    return appDelegate;
  }
  const property = appDelegate.match(TEMPLATE_FACTORY_PROPERTY);
  if (!property || !TEMPLATE_WINDOW_BLOCK.test(appDelegate)) {
    throw new Error(
      "with-scene-lifecycle: the AppDelegate no longer matches the Expo SDK 54 template. " +
        "Check whether Expo now adopts UIScene itself before updating this plugin."
    );
  }
  const indent = property[1];
  return appDelegate
    .replace(
      TEMPLATE_FACTORY_PROPERTY,
      `\n${indent}var reactNativeFactory: RCTReactNativeFactory?\n` +
        `${indent}${MARKER}: SceneDelegate starts React Native with these.\n` +
        `${indent}var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n`
    )
    .replace(
      TEMPLATE_WINDOW_BLOCK,
      `\n${indent}${indent}// The UIScene lifecycle: SceneDelegate creates the window and starts React Native.\n` +
        `${indent}${indent}self.launchOptions = launchOptions\n`
    );
}

function addSceneManifest(infoPlist) {
  return { ...infoPlist, UIApplicationSceneManifest: SCENE_MANIFEST };
}

const withSceneLifecycle = (config) => {
  config = withInfoPlist(config, (c) => {
    c.modResults = addSceneManifest(c.modResults);
    return c;
  });
  config = withAppDelegate(config, (c) => {
    if (c.modResults.language !== "swift") {
      throw new Error("with-scene-lifecycle: expected a Swift AppDelegate");
    }
    c.modResults.contents = adoptSceneLifecycle(c.modResults.contents);
    return c;
  });
  return IOSConfig.XcodeProjectFile.withBuildSourceFile(config, {
    filePath: "SceneDelegate.swift",
    contents: SCENE_DELEGATE_SWIFT,
    overwrite: true,
  });
};

module.exports = withSceneLifecycle;
module.exports.adoptSceneLifecycle = adoptSceneLifecycle;
module.exports.addSceneManifest = addSceneManifest;
module.exports.SCENE_DELEGATE_SWIFT = SCENE_DELEGATE_SWIFT;
